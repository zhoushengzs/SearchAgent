#!/usr/bin/env python3
"""Answer-conditioned demonstration planning using immutable recorded observations.

Teacher sees completed source trace+answer. Student exports see only the selected
prefix. All results are replayed from an evidence bank; never generated by a model.
Uses the existing OpenRouter client, without changing the old processing program.
"""
import argparse
import collections as C
import copy
import importlib.util
import json
import os
import sqlite3
import sys
from pathlib import Path

class Invalid(Exception): pass

def load_api(cfg):
    path=Path(cfg['existing_teacher_script']).resolve()
    sys.path.insert(0,str(path.parent))
    spec=importlib.util.spec_from_file_location('existing_teacher_api',path)
    mod=importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod

def config(path):
    cfg=json.loads(Path(path).read_text()); cfg['_config_dir']=str(Path(path).resolve().parent)
    return cfg

def prompt(cfg,name): return (Path(cfg['prompts_dir'])/(name+'.txt')).read_text()
def write(path,obj): Path(path).write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n')
def lines(path):
    with Path(path).open() as f:
        for n,line in enumerate(f,1): yield n,json.loads(line)

def prepare(cfg,limit):
    api=load_api(cfg); c=api.cleaner(cfg); target=Path(cfg['jobs_file'])
    if target.exists(): raise Invalid('Jobs already exist; choose a new jobs_file.')
    target.parent.mkdir(parents=True,exist_ok=True)
    jobs=[]; seen=set(); skipped=C.Counter()
    for ln,row in lines(cfg['source_train']):
        tid=row.get('trajectory_id')
        if not tid or tid in seen or not row.get('teacher_decision_json'): continue
        d=json.loads(row['teacher_decision_json'])
        if d.get('tool')!='finish' or row.get('sample_type') not in cfg['answer_source_types']: continue
        try:
            hist=c.history(row)
            if not cfg['min_source_actions']<=len(hist)<=cfg['max_source_actions']: continue
            prefix,st=c.parse_state(row)
            if st is None: continue
            bank=[]
            for a in hist:
                match=c.THINK.search(a['assistant']['value'])
                bank.append({'bank_step':a['step'],'call':a['call'],'result':a['result'],
                    'original_decision_note':json.loads(match.group(1)) if match and match.group(1).strip() else {}})
            job={'source_row':row,'bank':bank,'known_answer':d['arguments'],
                'answer_source':{'sample_type':row['sample_type'],'independently_proven_ground_truth':False},
                'provenance':{'file':cfg['source_train'],'line':ln,'trajectory_id':tid,'original_id':row['id']}}
            job['job_id']=api.digest(job)
            image_records=api.preflight_images({'base_row':row},cfg,False)
            context=teacher_context(job,cfg)
            if len(json.dumps(context,ensure_ascii=False))>cfg['max_context_characters']: raise Invalid('context_too_large')
            job['image_hashes']=[{'path':im['path'],'sha256':im['sha256']} for im in image_records]
            jobs.append(job); seen.add(tid)
        except (ValueError,KeyError,TypeError,Invalid,api.Invalid,c.NeedsReview) as e:
            skipped[str(e)]+=1
        if len(jobs)>=limit: break
    with target.open('w') as f:
        for job in jobs: f.write(json.dumps(job,ensure_ascii=False)+'\n')
    result={'jobs':len(jobs),'different_tasks':len(seen),'teacher_knows_complete_process_and_answer':True,
        'answer_source':'reviewed teacher final decisions; not claimed to be independent ground truth',
        'skipped':dict(skipped),'api_calls':0,'mode':'recorded_observation_replay'}
    write(target.with_suffix('.prepare.json'),result); print(json.dumps(result,ensure_ascii=False,indent=2))
    return jobs

def teacher_context(job,cfg):
    row=job['source_row']; api=load_api(cfg); c=api.cleaner(cfg)
    _,st=c.parse_state(row)
    return {'question':st['question'],'known_answer_for_teacher_only':job['known_answer'],'answer_source':job['answer_source'],
        'complete_recorded_process':job['bank'],'complete_source_state_for_teacher_only':st,
        'available_tools':api.native_tools(row,c), 'maximum_simulated_actions':cfg['max_simulated_actions'],
        'scenario_rules':{'one_demonstration':'a plausible initial hypothesis, locatable contradictory/missing evidence, a return to earlier evidence, and justified correction',
            'no_forced_backtracking':'return no_suitable_backtrack when the evidence bank cannot support a natural demonstration',
            'no_fabricated_observation':'select bank_step IDs only; if new results are needed return needs_execution',
            'new_numbering':'depends_on, trigger_steps, revisit_steps and final evidence_steps use simulated positions 1..N, not bank_step IDs; 0 means initial input'}}

def check_int_ids(values,allowed,name):
    if not isinstance(values,list) or any(not isinstance(x,int) or isinstance(x,bool) or x not in allowed for x in values):
        raise Invalid('Invalid '+name)

def assemble(job,plan,cfg):
    """Validate and render every student prefix, copying results only from the bank."""
    api=load_api(cfg); c=api.cleaner(cfg)
    if plan.get('status')!='ready': raise Invalid('Plan is not ready for replay/export')
    steps=plan.get('steps')
    if not isinstance(steps,list) or not 2<=len(steps)<=cfg['max_simulated_actions']: raise Invalid('Invalid simulated trace length')
    bank={x['bank_step']:x for x in job['bank']}
    original=job['source_row']; _,original_state=c.parse_state(original)
    budget=original_state['remaining_decisions']+len(job['bank'])
    if len(steps)>=budget: raise Invalid('Trace exceeds original decision budget')
    initial_ids={im.get('asset_id') for im in original_state.get('initial_views',[])}
    available_assets=set(initial_ids); known_urls=set(); first_uses=[]; hist=[]; allowed={0}; student_rows=[]
    attachments=[]; attachment_keys=set(); image_paths=[]; revisit_count=0
    original_images=original.get('images',[])
    def attach_at(old_step,new_step):
        for item in original_state.get('attached_images',[]):
            if item.get('observed_at_step')!=old_step: continue
            old_index=item['image_index']
            path=original_images[old_index-1]
            fingerprint=(path,item.get('sha256'),item.get('asset_id'),str(item.get('bbox')))
            if fingerprint in attachment_keys: continue
            attachment_keys.add(fingerprint); im=copy.deepcopy(item)
            image_paths.append(path); im['image_index']=len(image_paths); im['observed_at_step']=new_step; attachments.append(im)
    attach_at(0,0)
    def state_now():
        st={'question':original_state['question'],'initial_views':copy.deepcopy(original_state.get('initial_views',[])),
            'image_inventory':[{'asset_id':a,'origin':'initial_input' if a in initial_ids else 'recorded_replay'} for a in sorted(available_assets) if a],
            'tool_configuration':copy.deepcopy(original_state['tool_configuration']),'attached_images':copy.deepcopy(attachments),
            'remaining_decisions':budget-len(hist),'executed_prefix_step_ids':list(range(1,len(hist)+1))}
        text=''.join('img_%d: <image>\n'%i for i in range(1,len(image_paths)+1))
        return {'from':'human','value':text+c.STATE_MARKER+' Historical hypotheses can be wrong.\n'+json.dumps(st,ensure_ascii=False)}
    def prefix_row(index,decision,tail):
        row={k:copy.deepcopy(original[k]) for k in ('trajectory_id','system','tools','source','split') if k in original}
        row.update(id=original['trajectory_id']+':simulation:'+job['job_id'][:12]+':'+str(index),step=index,
            images=list(image_paths),teacher_decision_json=json.dumps(decision,ensure_ascii=False),sample_type='teacher_simulated_recorded_replay')
        metadata={k:decision[k] for k in ('rationale','information_need','gap_type','depends_on')}
        if decision['tool']=='finish': metadata.update(reasoning=decision['arguments']['reasoning'],evidence_steps=decision['arguments']['evidence_steps'])
        message={'from':'gpt','value':'<think>'+json.dumps(metadata,ensure_ascii=False)+'</think>\n'+tail}
        row['conversations']=[state_now()]
        for a in hist: row['conversations'].extend([copy.deepcopy(a['assistant']),copy.deepcopy(a['observation_message'])])
        row['conversations'].append(message)
        c.validate_row(row)
        return row,message
    for i,node in enumerate(steps,1):
        if set(node)-{'bank_step','rationale','information_need','gap_type','depends_on','behavior','trigger_steps','revisit_steps','hypothesis_before','hypothesis_after','error_context','supervise'}:
            raise Invalid('Unexpected step properties (observations must not be model-written)')
        b=bank.get(node.get('bank_step'))
        if b is None: raise Invalid('Unknown bank_step')
        if not isinstance(node.get('supervise'),bool) or not isinstance(node.get('error_context'),bool): raise Invalid('Missing supervision flags')
        if node['error_context'] and node['supervise']: raise Invalid('Known wrong decision cannot be a positive target')
        for key in ('depends_on','trigger_steps','revisit_steps'): check_int_ids(node.get(key),allowed,key)
        for key in ('rationale','information_need','gap_type','behavior'):
            if not isinstance(node.get(key),str) or not node[key].strip(): raise Invalid('Missing '+key)
        if node['gap_type'] not in ('visual','language','mixed','none'): raise Invalid('Unknown gap_type')
        if node['behavior'] not in ('explore','continue','reassess','revisit','recover'): raise Invalid('Unknown behavior')
        if node['behavior'] in ('reassess','revisit','recover'):
            if not node['trigger_steps'] or not node['revisit_steps']: raise Invalid('Backtracking needs an earlier evidence location and a trigger')
            if node.get('hypothesis_before') is None or node.get('hypothesis_after') is None: raise Invalid('Missing hypothesis update')
            revisit_count+=1
        call=copy.deepcopy(b['call']); tool=call['name']; args=call['arguments']; key=c.action_key(call)
        if hist and hist[-1]['key']==key:
            retry,_=c.classify_retry(hist,call)
            if not retry: raise Invalid('Unsupported consecutive same-argument repetition')
        if b['bank_step'] not in first_uses:
            if first_uses and b['bank_step']<first_uses[-1]: raise Invalid('First-time evidence cannot be introduced in reversed source order')
            first_uses.append(b['bank_step'])
        if args.get('asset_id') and args['asset_id'] not in available_assets: raise Invalid('Resource has not been obtained yet')
        if tool=='vs_visit' and args.get('url') not in known_urls: raise Invalid('URL has not been obtained yet')
        if tool=='vs_inspect_image' and args.get('image_url') and args['image_url'] not in known_urls: raise Invalid('Image URL has not been obtained yet')
        native=tool[3:] if tool.startswith('vs_') else tool
        decision={'tool':native,'arguments':args,**{k:node[k] for k in ('rationale','information_need','gap_type','depends_on')}}
        row,message=prefix_row(i,decision,'<tool_call>'+json.dumps(call,ensure_ascii=False)+'</tool_call>')
        if node['supervise']: student_rows.append(row)
        # Never ask the teacher to write or edit result content. Original observer
        # interpretations are not copied: they refer to the old path and numbering.
        obs={'step':i,'result':copy.deepcopy(b['result'])}
        hist.append({'step':i,'key':key,'call':call,'result':obs['result'],'assistant':message,
            'observation_message':{'from':'observation','value':json.dumps(obs,ensure_ascii=False)}})
        known_urls.update(api.all_urls(obs['result']))
        def add_assets(x):
            if isinstance(x,dict):
                if isinstance(x.get('asset_id'),str): available_assets.add(x['asset_id'])
                for value in x.values(): add_assets(value)
            elif isinstance(x,list):
                for value in x: add_assets(value)
        add_assets(obs['result']); attach_at(b['bank_step'],i); allowed.add(i)
    if not revisit_count: raise Invalid('A backtracking demonstration must contain a grounded reassessment or revisit')
    final=plan.get('final',{})
    if set(final)-{'answers','reasoning','evidence_steps'}: raise Invalid('Unexpected final properties')
    check_int_ids(final.get('evidence_steps'),allowed,'final evidence_steps')
    if not final['evidence_steps'] or not isinstance(final.get('answers'),list) or not final['answers'] or any(not isinstance(a,str) or not a.strip() for a in final['answers']): raise Invalid('Missing supported final answer')
    if not isinstance(final.get('reasoning'),str) or not final['reasoning'].strip(): raise Invalid('Missing final explanation')
    d={'tool':'finish','arguments':copy.deepcopy(final),'rationale':final['reasoning'],'information_need':'No remaining evidence needed','gap_type':'none','depends_on':final['evidence_steps']}
    row,_=prefix_row(len(hist)+1,d,'<response>'+'\n'.join(final['answers'])+'</response>')
    student_rows.append(row)
    return student_rows,{'backtracking_steps':revisit_count,'simulated_actions':len(steps),'supervised_prefixes':len(student_rows),
        'known_wrong_targets_published':False,'observations':'copied exactly from original bank results','new_live_tool_calls':0}

def request(job,cfg,model,role,plan=None):
    api=load_api(cfg); text=json.dumps(teacher_context(job,cfg),ensure_ascii=False)
    if plan is not None: text+='\nSIMULATED DEMONSTRATION TO REVIEW:\n'+json.dumps(plan,ensure_ascii=False)
    if len(text)>cfg['max_context_characters']: raise Invalid('Context too large; refusing silent truncation')
    content=[{'type':'text','text':text}]
    for im in api.preflight_images({'base_row':job['source_row']},cfg,True):
        content.extend([{'type':'text','text':'Original full-process image img_'+str(im['image_index'])},im['part']])
    return {'model':model,'messages':[{'role':'system','content':prompt(cfg,role)},{'role':'user','content':content}],
        'stream':False,'max_tokens':cfg['max_output_tokens'],'temperature':cfg.get('temperature',0.3),
        'provider':{'require_parameters':True},'response_format':{'type':'json_object'}}

def accepted(review):
    keys=['prefix_visibility_valid','answer_supported','backtrack_has_real_trigger','no_observation_fabrication','no_unnecessary_backtrack','wrong_steps_not_supervised']
    return review.get('verdict')=='accept' and all(review.get(k) is True for k in keys)

def run(cfg,args,client_override=None):
    api=load_api(cfg); jobs=[j for _,j in lines(cfg['jobs_file'])]
    for job in jobs:
        if job['job_id']!=api.digest({k:v for k,v in job.items() if k not in ('job_id','image_hashes')}): raise Invalid('Prepared job content changed')
    teacher=args.model or os.environ.get('OPENROUTER_MODEL') or cfg.get('teacher_model')
    reviewer=args.reviewer_model or os.environ.get('OPENROUTER_REVIEWER_MODEL') or cfg.get('reviewer_model') or teacher
    if not teacher: raise Invalid('Specify the OpenRouter model ID.')
    hashes=[]
    for job in jobs:
        records=api.preflight_images({'base_row':job['source_row']},cfg,False)
        current=[{'path':im['path'],'sha256':im['sha256']} for im in records]
        if current!=job['image_hashes']: raise Invalid('Source image changed since preparation')
        hashes.extend(current)
    fingerprint=api.digest({'config':{k:v for k,v in cfg.items() if not k.startswith('_')},'jobs':api.sha_file(cfg['jobs_file']),
        'teacher':teacher,'reviewer':reviewer,'prompts':[prompt(cfg,r) for r in ('teacher','reviewer')],
        'program':api.sha_file(__file__),'api_program':api.sha_file(cfg['existing_teacher_script']),'images':hashes})
    out=Path(cfg['runs_dir'])/fingerprint[:16]
    if args.dry_run:
        p=request(jobs[0],cfg,teacher,'teacher') if jobs else {}
        print(json.dumps({'jobs':len(jobs),'teacher_knows_answer':True,'payload_bytes':len(json.dumps(p).encode()),'network_calls':0,'future_run_dir':str(out)},ensure_ascii=False,indent=2)); return out
    client=client_override or api.OpenRouter(os.environ.get('OPENROUTER_API_KEY'),cfg,args.max_api_calls)
    if client_override is None: api.verify_models(client.models(),[teacher,reviewer],True)
    out.mkdir(parents=True,exist_ok=True)
    write(out/'run_metadata.json',{'fingerprint':fingerprint,'mode':'answer_conditioned_recorded_replay','teacher':teacher,'reviewer':reviewer,
        'jobs_file':cfg['jobs_file'],'new_live_tool_calls':0,'not_a_claim_of_independent_ground_truth':True})
    db=sqlite3.connect(out/'results.sqlite')
    db.execute('CREATE TABLE IF NOT EXISTS results (id TEXT PRIMARY KEY,status TEXT,plan TEXT,review TEXT,usage TEXT,error TEXT)')
    done=0
    for job in jobs:
        old=db.execute('SELECT status,plan,usage FROM results WHERE id=?',(job['job_id'],)).fetchone()
        if old and old[0]!='generated': continue
        if done>=args.limit or client.calls>=args.max_api_calls: break
        done+=1; plan=None; review=None; usage=[]; status='error'; error=None; fatal=False
        try:
            if old:
                plan=json.loads(old[1]); usage=json.loads(old[2])
            else:
                raw,meta=client.chat(request(job,cfg,teacher,'teacher')); usage.append({'role':'teacher',**meta}); plan=api.parse_reply(raw)
            if plan.get('status') in ('needs_execution','no_suitable_backtrack','answer_conflict'):
                status=plan['status']
            else:
                assemble(job,plan,cfg)
                db.execute('INSERT OR REPLACE INTO results VALUES (?,?,?,?,?,?)',(job['job_id'],'generated',json.dumps(plan,ensure_ascii=False),None,json.dumps(usage),None)); db.commit()
                raw,meta=client.chat(request(job,cfg,reviewer,'reviewer',plan)); usage.append({'role':'reviewer',**meta}); review=api.parse_reply(raw)
                status='accepted' if accepted(review) else 'review_rejected'
        except api.APIError as e:
            error=str(e); status='generated' if plan and plan.get('status')=='ready' else 'error'; fatal=e.status in (400,401,402,403,404)
        except Exception as e:
            error=str(e)
            if error=='api_call_limit_reached' and plan is not None: status='generated'
        db.execute('INSERT OR REPLACE INTO results VALUES (?,?,?,?,?,?)',(job['job_id'],status,json.dumps(plan,ensure_ascii=False) if plan else None,
            json.dumps(review,ensure_ascii=False) if review else None,json.dumps(usage),error)); db.commit()
        print(json.dumps({'job':job['job_id'][:12],'status':status,'error':error,'api_calls':client.calls},ensure_ascii=False),flush=True)
        if fatal: break
    by_id={j['job_id']:j for j in jobs}; exported=[]; records=[]; statuses=C.Counter()
    for jid,status,p,r,u,e in db.execute('SELECT id,status,plan,review,usage,error FROM results ORDER BY id'):
        statuses[status]+=1
        if status=='accepted':
            review=json.loads(r); plan=json.loads(p)
            if not accepted(review): raise Invalid('Cached review no longer meets acceptance criteria')
            rows,validation=assemble(by_id[jid],plan,cfg); exported.extend(rows)
            records.append({'job_id':jid,'source':by_id[jid]['provenance'],'answer_source':by_id[jid]['answer_source'],'plan':plan,'review':review,'validation':validation,'usage':json.loads(u),
                'observation_mode':'original_record_replay','exported_ids':[x['id'] for x in rows]})
    db.close()
    for filename,items in [('student_sft_candidates.jsonl',exported),('simulation_provenance.jsonl',records)]:
        temp=out/(filename+'.tmp')
        with temp.open('w') as f:
            for item in items: f.write(json.dumps(item,ensure_ascii=False)+'\n')
        temp.replace(out/filename)
    summary={'run_dir':str(out),'statuses':dict(statuses),'student_samples':len(exported),'api_calls_this_run':client.calls,
        'new_live_tool_calls':0,'merged_into_clean_dataset':False}
    write(out/'summary.json',summary); print(json.dumps(summary,ensure_ascii=False,indent=2)); return out

def doctor(cfg):
    api=load_api(cfg); api.cleaner(cfg); jobs=[j for _,j in lines(cfg['jobs_file'])]; total=0
    for j in jobs:
        if j.get('job_id')!=api.digest({k:v for k,v in j.items() if k not in ('job_id','image_hashes')}): raise Invalid('Job content changed')
        total+=len(api.preflight_images({'base_row':j['source_row']},cfg,False)); teacher_context(j,cfg)
    for name in ('teacher','reviewer'): prompt(cfg,name)
    result={'jobs':len(jobs),'images':total,'offline':True,'model_calls':0,'teacher_receives_complete_process_and_answer':True}
    print(json.dumps(result,ensure_ascii=False,indent=2)); return result

def main():
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('command',choices=['prepare','doctor','run']); p.add_argument('--config',type=Path,required=True)
    p.add_argument('--limit',type=int,default=3); p.add_argument('--model'); p.add_argument('--reviewer-model'); p.add_argument('--max-api-calls',type=int,default=8); p.add_argument('--dry-run',action='store_true')
    args=p.parse_args(); cfg=config(args.config)
    if args.command=='prepare': return prepare(cfg,args.limit)
    if args.command=='doctor': return doctor(cfg)
    return run(cfg,args)
if __name__=='__main__':
    try: main()
    except Exception as e:
        print('STOP:',str(e),file=sys.stderr); sys.exit(2)
